#!/usr/bin/env python3
"""Export the BDQ baseline from rs.tdwg.org into this repository (deployment_rs_tdwg_org.md, Section 13.1).

rs.tdwg.org is the source of truth for the terms and versions of the seven BDQ vocabularies, the
GUID tables behind the bdqtest graphs, the bdqffdq axioms, and the document metadata. The build in
this repository still reads its own copies of the vocabularies. This tool regenerates those copies
from one pinned rs.tdwg.org commit, so they are generated, read-only exports rather than files
edited by hand:

    tg2/_review/vocabulary/{bdqdim,bdqenh,bdqcrit,bdquc,bdqval,bdqtest}_term_versions.csv
        the current version of each term, in the published BDQ column names;
    tg2/_review/vocabulary/bdqffdq.owl and tg2/_review/dist/bdqffdq.{ttl,rdf,jsonld}
        the ontology, generated by rs.tdwg.org's process/build_ontology.py;
    tg2/core/{TG2_tests_additional_guids,information_element_guids,TG2_policy_guids,TG2_citation_guids}.csv
        the GUID tables of the latest release that has each one (process/bdq-revisions/*/bdqtest-graph-inputs/);
    tg2/_review/vocabulary/rs_tdwg_org_baseline.json
        provenance: the rs.tdwg.org repository, ref, and commit exported, and the files written.

Do not edit these files by hand: make changes in rs.tdwg.org (process/bdq-revisions/ on the
bdq-source branch during the review; see its README, "Changing a Test") and export again. Proposed
changes that are not yet accepted belong in the proposed layer (Section 13.1), not in these files.

The rs.tdwg.org source is configurable, as for the Darwin Core build: a local checkout (--rs, the
ref is exported with `git archive`, so uncommitted changes are ignored) or GitHub (the default,
tdwg/rs.tdwg.org at --ref). The ref is resolved to a commit, which is recorded.

Column mappings back to the published names: bdqtest uses rs.tdwg.org's
process/bdq-revisions/bdqtest_columns.py (Section 10.8), read from the exported commit; the five
simple vocabularies use SIMPLE_COLUMNS below, the inverse of process/bdq-revisions/bdq_to_rs.py.

Usage (from tg2/_make_review):
    python3 export_rs_baseline.py                      # tdwg/rs.tdwg.org, branch bdq, from GitHub
    python3 export_rs_baseline.py --rs ../../../rs.tdwg.org --ref bdq
    python3 export_rs_baseline.py --ref <commit> --check   # report differences, write nothing

Requires rdflib (for the ontology generator).
"""
import argparse, csv, datetime, hashlib, importlib.util, io, json, os, pathlib, re, shutil
import subprocess, sys, tarfile, tempfile, urllib.request

HERE = pathlib.Path(__file__).resolve().parent
TG2 = HERE.parent
VOCABULARY = TG2 / '_review' / 'vocabulary'
DIST = TG2 / '_review' / 'dist'
CORE = TG2 / 'core'
GITHUB_REPO = 'tdwg/rs.tdwg.org'

SIMPLE_VOCABULARIES = ['bdqdim', 'bdqenh', 'bdqcrit', 'bdquc', 'bdqval']
# The published columns of each simple vocabulary's term-version file, in their order.
SIMPLE_HEADERS = {
    'bdqdim': ['iri', 'term_localName', 'prefLabel', 'label', 'definition', 'comments', 'organized_in', 'issued',
               'status', 'rdf_type', 'term_iri', 'flags', 'controlled_value_string'],
    'bdqenh': None, 'bdqcrit': None,  # as bdqdim
    'bdquc': None,                    # read from the existing file if present, else bdqdim's plus the two below
    'bdqval': ['iri', 'term_iri', 'term_localName', 'label', 'prefLabel', 'definition', 'organized_in', 'issued',
               'status', 'rdf_type', 'comments', 'flags', 'controlled_value_string'],
}
GUID_TABLES = ['TG2_tests_additional_guids.csv', 'information_element_guids.csv', 'TG2_policy_guids.csv',
               'TG2_citation_guids.csv']
CURIES = {
    'http://www.w3.org/2004/02/skos/core#': 'skos:',
    'https://rs.tdwg.org/bdqffdq/terms/': 'bdqffdq:',
    'http://www.w3.org/2000/01/rdf-schema#': 'rdfs:',
    'http://www.w3.org/2002/07/owl#': 'owl:',
}
XHTML_DIV = re.compile(r'<div xmlns="http://www\.w3\.org/1999/xhtml">(.*)</div>', re.S)


def curie(iri):
    for namespace, prefix in CURIES.items():
        if iri.startswith(namespace):
            return prefix + iri[len(namespace):]
    return iri


def unwrap(xml_literal):
    """The text of an rdf:XMLLiteral that bdq_to_rs.py wrapped in an XHTML div."""
    match = XHTML_DIV.fullmatch(xml_literal)
    return match.group(1) if match else xml_literal


def organized_in(vocabulary, types):
    """The List of Terms grouping (a presentation choice of this repository's build, not term data):
    the term list for the dimension, enhancement, and criterion vocabularies; otherwise the first type,
    with skos:Concept grouped as Data."""
    if vocabulary in ('bdqdim', 'bdqenh', 'bdqcrit'):
        return f'https://rs.tdwg.org/{vocabulary}/terms/'
    first = curie(types[0]) if types else ''
    return 'Data' if first == 'skos:Concept' else first


def read_rows(path):
    with open(path, newline='', encoding='utf-8') as f:
        return list(csv.DictReader(f))


def current_versions(source, dataset):
    """The recommended (current) version of each term of a dataset."""
    rows = read_rows(source / f'{dataset}-versions' / f'{dataset}-versions.csv')
    return {r['term_localName']: r for r in rows if r['version_status'] == 'recommended'}


UNQUOTED = re.compile(r'|\d+|\d{4}-\d{2}-\d{2}')


def csv_field(value):
    """Every field is quoted except empty ones, integers, and dates, as in the published bdqtest file."""
    if UNQUOTED.fullmatch(value):
        return value
    return '"' + value.replace('"', '""') + '"'


def published_order(path):
    """The term_localName order of an existing published file, so that an export changes only what
    changed in rs.tdwg.org; terms not yet in it follow, sorted."""
    if not path.exists():
        return []
    return [r['term_localName'] for r in read_rows(path)]


def csv_text(header, rows, order=()):
    position = {name: i for i, name in enumerate(order)}
    rows = sorted(rows, key=lambda r: (position.get(r['term_localName'], len(position)), r['term_localName']))
    lines = [','.join(csv_field(column) for column in header)]
    for row in rows:
        lines.append(','.join(csv_field(row.get(column, '')) for column in header))
    return '\n'.join(lines) + '\n'


def simple_vocabulary(source, vocabulary, existing_header):
    header = SIMPLE_HEADERS[vocabulary] or existing_header or SIMPLE_HEADERS['bdqdim']
    terms = read_rows(source / vocabulary / f'{vocabulary}.csv')
    versions = current_versions(source, vocabulary)
    rows = []
    for term in terms:
        name = term['term_localName']
        version = versions[name]
        types = [t for t in (term['type'], term['type1']) if t]
        rows.append({
            'iri': version['version'],
            'term_iri': term['term_isDefinedBy'] + name,
            'term_localName': name,
            'label': term['label'],
            'prefLabel': term['prefLabel'],
            'definition': term['definition'],
            'comments': unwrap(term['notes']),
            'scopeNote': term['usage'],
            'hasFitnessRequirements': unwrap(term['hasFitnessRequirements']),
            'organized_in': organized_in(vocabulary, types),
            'issued': version['version_issued'],
            'status': version['version_status'],
            'rdf_type': ', '.join(curie(t) for t in types),
            'flags': '',
            'controlled_value_string': term['controlled_value_string'],
        })
    return csv_text(header, rows, published_order(VOCABULARY / f'{vocabulary}_term_versions.csv'))


def bdqtest(source):
    spec = importlib.util.spec_from_file_location('bdqtest_columns',
                                                  source / 'process' / 'bdq-revisions' / 'bdqtest_columns.py')
    columns = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(columns)
    terms = read_rows(source / 'bdqtest' / 'bdqtest.csv')
    versions = current_versions(source, 'bdqtest')
    header = list(columns.COLUMNS)
    existing = VOCABULARY / 'bdqtest_term_versions.csv'
    if existing.exists():  # keep the published column order
        with open(existing, newline='', encoding='utf-8') as f:
            published = next(csv.reader(f))
        if set(published) == set(header):
            header = published
    rows = []
    for term in terms:
        name = term['term_localName']
        version = versions[name]
        row = {published_name: term[rs_name] for published_name, rs_name in columns.COLUMNS.items() if rs_name}
        row['iri'] = version['version']
        row['term_iri'] = term['term_isDefinedBy'] + name
        row['issued'] = version['version_issued']
        rows.append(row)
    return csv_text(header, rows, published_order(existing))


def guid_tables(source):
    """Each GUID table from the latest release directory that has it."""
    out = {}
    for table in GUID_TABLES:
        found = sorted(source.glob(f'process/bdq-revisions/bdq-revisions-20*/bdqtest-graph-inputs/{table}'))
        if not found:
            sys.exit(f'no {table} in {source}/process/bdq-revisions/*/bdqtest-graph-inputs/')
        out[table] = (found[-1].read_bytes(), str(found[-1].relative_to(source)))
    return out


def ontology(source, work):
    out = work / 'ontology'
    subprocess.run([sys.executable, 'build_ontology.py', '../bdqffdq', '--output-dir', str(out), '--no-robot'],
                   cwd=source / 'process', check=True, stdout=subprocess.DEVNULL)
    return {suffix: (out / f'bdqffdq.{suffix}').read_bytes() for suffix in ('ttl', 'rdf', 'jsonld')}


def fetch_source(args, work):
    """Extract the ref into work/rs and return (path, commit, repository)."""
    target = work / 'rs'
    target.mkdir()
    if args.rs:
        checkout = pathlib.Path(args.rs).resolve()
        commit = subprocess.run(['git', '-C', str(checkout), 'rev-parse', '--verify', args.ref + '^{commit}'],
                                check=True, capture_output=True, text=True).stdout.strip()
        archive = subprocess.run(['git', '-C', str(checkout), 'archive', '--format=tar', commit],
                                 check=True, capture_output=True).stdout
        repository = subprocess.run(['git', '-C', str(checkout), 'remote', 'get-url', 'origin'],
                                    capture_output=True, text=True).stdout.strip() or str(checkout)
        repository = re.sub(r'^git@github\.com:(.*?)(\.git)?$', r'https://github.com/\1', repository)
    else:
        request = urllib.request.Request(f'https://api.github.com/repos/{GITHUB_REPO}/commits/{args.ref}',
                                         headers={'Accept': 'application/vnd.github+json'})
        if os.environ.get('GITHUB_TOKEN'):  # e.g. in GitHub Actions, to avoid the anonymous rate limit
            request.add_header('Authorization', 'Bearer ' + os.environ['GITHUB_TOKEN'])
        with urllib.request.urlopen(request, timeout=60) as r:
            commit = json.load(r)['sha']
        with urllib.request.urlopen(f'https://codeload.github.com/{GITHUB_REPO}/tar.gz/{commit}', timeout=600) as r:
            archive = r.read()
        repository = f'https://github.com/{GITHUB_REPO}'
    with tarfile.open(fileobj=io.BytesIO(archive)) as tar:
        members = tar.getmembers()
        if not args.rs:  # GitHub archives have a top-level directory
            for member in members:
                member.name = member.name.split('/', 1)[1] if '/' in member.name else ''
            members = [m for m in members if m.name]
        tar.extractall(target, members=members, filter='data')
    return target, commit, repository


def main():
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--rs', help='local rs.tdwg.org checkout (default: GitHub)')
    parser.add_argument('--ref', default='bdq', help='branch, tag, or commit to export (default: bdq)')
    parser.add_argument('--check', action='store_true', help='report which files would change; write nothing')
    args = parser.parse_args()

    with tempfile.TemporaryDirectory() as tmp:
        work = pathlib.Path(tmp)
        source, commit, repository = fetch_source(args, work)
        outputs = {}
        for vocabulary in SIMPLE_VOCABULARIES:
            path = VOCABULARY / f'{vocabulary}_term_versions.csv'
            existing_header = None
            if path.exists():
                with open(path, newline='', encoding='utf-8') as f:
                    existing_header = next(csv.reader(f))
            outputs[path] = simple_vocabulary(source, vocabulary, existing_header).encode('utf-8')
        outputs[VOCABULARY / 'bdqtest_term_versions.csv'] = bdqtest(source).encode('utf-8')
        sources = {}
        for table, (content, origin) in guid_tables(source).items():
            outputs[CORE / table] = content
            sources[f'tg2/core/{table}'] = origin
        serializations = ontology(source, work)
        outputs[VOCABULARY / 'bdqffdq.owl'] = serializations['ttl']
        for suffix, content in serializations.items():
            outputs[DIST / f'bdqffdq.{suffix}'] = content

    changed = [path for path, content in outputs.items() if not path.exists() or path.read_bytes() != content]
    label = f'{repository} {args.ref} ({commit})'
    if args.check:
        print(f'Baseline export from {label}: {len(changed)} of {len(outputs)} files would change')
        for path in changed:
            print('  ' + str(path.relative_to(TG2.parent)))
        if changed:
            print('These files are generated from rs.tdwg.org and must not be edited by hand. If rs.tdwg.org has '
                  'changed, run tg2/_make_review/export_rs_baseline.py, review, and commit the result; if a file here '
                  'was edited, make the change in rs.tdwg.org instead (tg2/README.md, sources of truth).')
        return 1 if changed else 0
    for path in changed:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(outputs[path])
    provenance = {
        'description': 'Generated by tg2/_make_review/export_rs_baseline.py: do not edit the files listed; '
                       'change rs.tdwg.org and export again (deployment_rs_tdwg_org.md, Section 13.1).',
        'repository': repository,
        'ref': args.ref,
        'commit': commit,
        'exported': datetime.datetime.now(datetime.timezone.utc).strftime('%Y-%m-%dT%H:%M:%SZ'),
        'files': {str(path.relative_to(TG2.parent)): hashlib.sha256(content).hexdigest()
                  for path, content in sorted(outputs.items())},
        'sources': sources,
    }
    (VOCABULARY / 'rs_tdwg_org_baseline.json').write_text(json.dumps(provenance, indent=2) + '\n', encoding='utf-8')
    print(f'Baseline export from {label}: {len(changed)} of {len(outputs)} files changed')
    for path in changed:
        print('  ' + str(path.relative_to(TG2.parent)))
    return 0


if __name__ == '__main__':
    sys.exit(main())
